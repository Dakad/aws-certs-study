             LAB_BAD_WRITE_EPOCH LAB_BAD_WRITE_TIME \
             LAB_RESTORED LAB_RESTORE_TARGET_LABEL \
             LAB_RESTORE_REQUEST_EPOCH LAB_RESTORE_AVAILABLE_EPOCH \
             LAB_RESTORE_SQL_EPOCH LAB_RESTORE_ELAPSED_AVAILABLE LAB_RESTORE_ELAPSED_SQL \
             LAB_PITR LAB_PITR_TARGET_TIME LAB_PITR_TARGET_EPOCH \
             LAB_PITR_REQUEST_EPOCH LAB_PITR_AVAILABLE_EPOCH \
             LAB_PITR_SQL_EPOCH LAB_PITR_ELAPSED_AVAILABLE LAB_PITR_ELAPSED_SQL \
