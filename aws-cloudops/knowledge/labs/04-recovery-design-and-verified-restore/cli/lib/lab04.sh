# ------------------------------------------------------------------ waiting
lab_instance_status() {
  aws rds describe-db-instances --db-instance-identifier "$1" \
    --query 'DBInstances[0].DBInstanceStatus' --output text 2>/dev/null || echo unknown
}

lab_snapshot_status() {
  aws rds describe-db-snapshots --db-snapshot-identifier "$1" \
    --query 'DBSnapshots[0].Status' --output text 2>/dev/null || echo unknown
}

# One scalar member at a time. `--output text` on a multi-key projection prints
# values in an order that is not worth relying on, and this lab must not depend
# on that.
lab_snap_field() {
  aws rds describe-db-snapshots --db-snapshot-identifier "$1" \
    --query "DBSnapshots[0].$2" --output text 2>/dev/null || echo None
}

lab_instance_field() {
  aws rds describe-db-instances --db-instance-identifier "$1" \
    --query "DBInstances[0].$2" --output text 2>/dev/null || echo None
}

# Poll until an instance reports `available`. Prints every status transition and
# exits non-zero on timeout, so a half-finished restore is never mistaken for a
# finished one.
lab_wait_instance() {
  local id="$1" label="$2" timeout="${3:-2400}"
  local start now elapsed last="" status
  start="$(lab_epoch)"
  echo "  waiting for $label ($id) to report available; timeout ${timeout}s"
  while :; do
    now="$(lab_epoch)"
    elapsed=$(( now - start ))
    status="$(lab_instance_status "$id")"
    if [[ "$status" != "$last" ]]; then
      printf '    [%4ss] %s: %s\n' "$elapsed" "$label" "$status"
      last="$status"
    fi
    [[ "$status" == "available" ]] && return 0
    if [[ $(( elapsed )) -ge $(( timeout )) ]]; then
      printf '    [%4ss] TIMEOUT: %s is %s, not available\n' "$elapsed" "$label" "$status" >&2
      echo "    Inspect before deleting: aws rds describe-db-instances --db-instance-identifier $id" >&2
      return 1
    fi
    sleep 15
  done
}

lab_wait_snapshot() {
  local id="$1" label="$2" timeout="${3:-1800}"
  local start now elapsed last="" status
  start="$(lab_epoch)"
  echo "  waiting for $label ($id) to finish; timeout ${timeout}s"
  while :; do
    now="$(lab_epoch)"
    elapsed=$(( now - start ))
    status="$(lab_snapshot_status "$id")"
    if [[ "$status" != "$last" ]]; then
      printf '    [%4ss] %s: %s\n' "$elapsed" "$label" "$status"
      last="$status"
    fi
    case "$status" in
      available|completed) return 0 ;;
    esac
    if [[ $(( elapsed )) -ge $(( timeout )) ]]; then
      printf '    [%4ss] TIMEOUT: %s is %s\n' "$elapsed" "$label" "$status" >&2
      return 1
    fi
    sleep 15
  done
}

# Poll until the instance answers a trivial SQL query. "available" is a
# control-plane statement; answering a query is the usability statement, and the
# RTO is only met at the second one.
lab_wait_sql() {
  local host="$1" port="$2" label="$3" timeout="${4:-900}"
  local start now elapsed
  start="$(lab_epoch)"
  echo "  waiting for $label to answer a query; timeout ${timeout}s"
  while :; do
    now="$(lab_epoch)"
    elapsed=$(( now - start ))
    if lab_sql "$host" "$port" "SELECT 1;" >/dev/null 2>&1; then
      printf '    [%4ss] %s answered a query\n' "$elapsed" "$label"
      return 0
    fi
    if [[ $(( elapsed )) -ge $(( timeout )) ]]; then
      printf '    [%4ss] TIMEOUT: %s never answered a query\n' "$elapsed" "$label" >&2
      echo "    The instance may still be starting, or the security group may not" >&2
      echo "    allow this machine. Both are findings — record which one." >&2
      return 1
    fi
    sleep 10
  done
}

# ------------------------------------------------------------------- SQL
# Runs one SQL string and prints bare pipe-separated values. Needs psql, or
# docker so the official postgres image can supply psql.
lab_sql() {
  local host="$1" port="$2" sql="$3"
  : "${LAB_DB_PASSWORD:?}"
  if command -v psql >/dev/null 2>&1; then
    PGPASSWORD="$LAB_DB_PASSWORD" PGOPTIONS='-c timezone=UTC' \
      psql -X -q -t -A -F '|' -v ON_ERROR_STOP=1 \
        -h "$host" -p "$port" -U "$LAB_DB_USER" -d "$LAB_DB_NAME" -c "$sql"
  elif command -v docker >/dev/null 2>&1; then
    docker run --rm -e PGPASSWORD -e 'PGOPTIONS=-c timezone=UTC' \
      "${LAB_PG_IMAGE:-postgres:17-alpine}" \
      psql -X -q -t -A -F '|' -v ON_ERROR_STOP=1 \
        -h "$host" -p "$port" -U "$LAB_DB_USER" -d "$LAB_DB_NAME" -c "$sql"
  else
    lab_die "need psql (brew install libpq) or docker to run SQL"
  fi
}

# ------------------------------------------------------------- verification
# The canary query. Counts, a checksum, the newest good row and the first five
# rows together answer "is this the copy I think it is, and how fresh is it".
lab_verify_data() {
  local host="$1" port="$2" expect_good="$3" expect_poison="$4" \
        expect_first5="$5" expect_checksum="$6" expect_newest="$7"
  local row good poison newest checksum first5 total
  row="$(lab_sql "$host" "$port" "
SELECT (count(*) FILTER (WHERE kind = 'good'))::bigint,
       (count(*) FILTER (WHERE kind = 'poison'))::bigint,
       to_char(max(written_at) FILTER (WHERE kind = 'good'), 'YYYY-MM-DD HH24:MI:SS'),
       sum(payload) FILTER (WHERE kind = 'good'),
       (count(*) FILTER (WHERE kind = 'good' AND id <= 5))::bigint,
       count(*)::bigint
FROM public.lab04_events;")"
  IFS='|' read -r good poison newest checksum first5 total <<< "$row"
  [[ -n "${good:-}" ]] || lab_die "verification query returned nothing: $row"

  echo "  canary query against $host:$port"
  printf '    %-34s %-24s %s\n' "good rows" "$good" "expected $expect_good"
  printf '    %-34s %-24s %s\n' "poison rows" "$poison" "expected $expect_poison"
  printf '    %-34s %-24s %s\n' "checksum(sum payload)" "$checksum" "expected $expect_checksum"
  printf '    %-34s %-24s %s\n' "rows 1-5 still present" "$first5" "expected $expect_first5"
  printf '    %-34s %-24s %s\n' "newest good row" "$newest" "expected ${expect_newest:-any}"
  printf '    %-34s %-24s\n' "total rows" "$total"

  local failed=0
  cmp_num() {
    if [[ "$2" == "$3" ]]; then
      printf '    PASS %s = %s\n' "$1" "$2"
    else
      printf '    FAIL %s = %s (expected %s)\n' "$1" "$2" "$3"
      failed=1
    fi
  }
  cmp_num "good rows" "$good" "$expect_good"
  cmp_num "poison rows" "$poison" "$expect_poison"
  cmp_num "checksum" "$checksum" "$expect_checksum"
  cmp_num "rows 1-5" "$first5" "$expect_first5"
  if [[ -n "${expect_newest:-}" && "$newest" != "$expect_newest" ]]; then
    printf '    INFO newest good row is %s; the run recorded %s (a few seconds of\n' "$newest" "$expect_newest"
    printf '         write drift is normal, an empty value is not)\n'
  fi
  if [[ "$failed" -eq 0 ]]; then
    echo "    VERDICT: this copy matches what was claimed. The restore is proven."
  else
    echo "    VERDICT: this copy does NOT match the claim. Do not call it recovered."
  fi
  return "$failed"
}
