#!/usr/bin/env bash
# Lab 04 shared helpers — sourced by the numbered scripts, never executed.
#
# Two jobs:
#   1. Remember one run's identifiers so every script agrees on them. The run
#      file is `cli/.env.lab04-run`, which the repository .gitignore already
#      covers with its `.env.*` rule. It holds the lab master password, so
#      never commit it and never paste it anywhere.
#   2. Poll AWS for state changes with a visible timeout instead of sleeping
#      and assuming.
#
# bash 3.2 compatible: no mapfile, no arrays, no ${var^^}. Verified on the
# macOS system bash.
#
# Waiters: this CLI has rds wait db-instance-available, db-instance-deleted,
# db-snapshot-available, db-snapshot-completed and db-snapshot-deleted
# (`aws rds wait help`). Each caps out at 40 attempts x 15s, roughly ten
# minutes, which a restore can exceed. lab_wait_instance/lab_wait_snapshot
# below are explicit polling loops so the timeout is visible and the exit
# status is meaningful; teardown uses db-instance-deleted where the wait is
# short and bounded.

LAB_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
RUN_FILE="${LAB_RUN_FILE:-$LAB_DIR/.env.lab04-run}"

lab_die() {
  echo "ERROR: $*" >&2
  exit 1
}

lab_need_profile() {
  [[ -n "${AWS_PROFILE:-}" ]] || lab_die "set AWS_PROFILE to the authorized profile first"
  [[ -n "${AWS_REGION:-}" ]] || export AWS_REGION="us-east-1"
}

lab_need_cmd() {
  command -v "$1" >/dev/null 2>&1 || lab_die "'$1' is required but not installed"
}

lab_utc_now() { date -u +%Y-%m-%dT%H:%M:%SZ; }
lab_epoch() { date -u +%s; }

# ISO 8601 UTC from an epoch value. Tries BSD date, then GNU date, then python3.
lab_iso_from_epoch() {
  local e="$1" out=""
  out="$(date -u -r "$e" +%Y-%m-%dT%H:%M:%SZ 2>/dev/null || true)"
  [[ -n "$out" ]] || out="$(date -u -d "@$e" +%Y-%m-%dT%H:%M:%SZ 2>/dev/null || true)"
  [[ -n "$out" ]] || out="$(python3 -c 'import sys,time;print(time.strftime("%Y-%m-%dT%H:%M:%SZ",time.gmtime(int(sys.argv[1]))))' "$e" 2>/dev/null || true)"
  [[ -n "$out" ]] || lab_die "could not convert epoch $e to a timestamp"
  printf '%s\n' "$out"
}

# Epoch from an AWS ISO timestamp such as 2026-10-03T18:42:03.123456Z.
lab_epoch_from_iso() {
  local iso="$1" clean out=""
  [[ -n "$iso" ]] || return 1
  clean="$(printf '%s' "$iso" | sed 's/\.[0-9]*Z*$//; s/Z$//; s/+00:00$//')"
  out="$(date -u -j -f '%Y-%m-%dT%H:%M:%S' "$clean" +%s 2>/dev/null || true)"
  [[ -n "$out" ]] || out="$(date -u -d "$clean UTC" +%s 2>/dev/null || true)"
  [[ -n "$out" ]] || out="$(python3 -c 'import sys,calendar,time;print(calendar.timegm(time.strptime(sys.argv[1],"%Y-%m-%dT%H:%M:%S")))' "$clean" 2>/dev/null || true)"
  [[ -n "$out" ]] || return 1
  printf '%s\n' "$out"
}

lab_hhmm() {
  local m=$(( $1 % 1440 ))
  printf '%02d:%02d' $(( m / 60 )) $(( m % 60 ))
}

# Print "<day> <backup_window> <maintenance_window>" for an RDS instance.
# Both windows are 30 minutes, are in UTC, and must not overlap or cross
# midnight, so they are derived from one lead time. Override with
# BACKUP_WINDOW / MAINTENANCE_WINDOW if AWS rejects them for an account-specific
# reason; the override values are echoed back so the record shows what ran.
lab_compute_windows() {
  local now lead b day
  now="$(lab_epoch)"
  lead="${LAB_BACKUP_LEAD_SECONDS:-900}"
  b=$(( (now + lead) / 300 * 300 ))
  while [[ $(( b - now )) -lt 600 ]]; do b=$(( b + 300 )); done
  day="$(date -u +%a)"
  if [[ -n "${BACKUP_WINDOW:-}" && -n "${MAINTENANCE_WINDOW:-}" ]]; then
    printf '%s %s %s\n' "$day" "$BACKUP_WINDOW" "$MAINTENANCE_WINDOW"
    return 0
  fi
  if [[ $(( (b + 65) / 1440 )) -ne $(( b / 1440 )) ]]; then
    # The derived windows would cross midnight UTC, which RDS does not accept.
    b=$(( (now / 1440 ) * 1440 + 10800 ))   # today 03:00 UTC
    if [[ $(( b - now )) -lt 1800 ]]; then
      b=$(( b + 86400 ))
      echo "  NOTE: no room for a 30-minute backup window before midnight UTC." >&2
      echo "        Using tomorrow's window, so the first automated backup will" >&2
      echo "        NOT run during this session. Steps 07 will report that." >&2
    else
      echo "  NOTE: using the fixed 03:00 UTC window; the derived one crossed midnight." >&2
    fi
  fi
  printf '%s %s %s-%s\n' "$day" \
    "$(lab_hhmm "$b")-$(lab_hhmm $(( b + 1800 )))" \
    "$(lab_hhmm $(( b + 2100 )))" \
    "$(lab_hhmm $(( b + 3900 )))"
}

